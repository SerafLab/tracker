import { expect, test } from '@playwright/test'

for (const width of [320, 1280]) {
  test(`deletes cards and statuses with safe keyboard focus and persistent order at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/tracker/')
    const projectName = page.getByRole('textbox', { name: /^(Новый проект|Название проекта)$/ })
    if (await projectName.count() === 0) await page.getByRole('button', { name: 'Создать проект' }).click()
    await projectName.fill('Удаление')
    await page.getByRole('button', { name: 'Создать проект' }).click()
    for (const name of ['Первый', 'Второй']) {
      await page.getByRole('button', { name: 'Добавить статус' }).first().click()
      await page.getByLabel('Название статуса').fill(name)
      await page.getByRole('button', { name: 'Создать статус' }).click()
      await expect(page.getByRole('dialog')).toBeHidden()
    }
    const first = page.locator('.status-column').filter({ has: page.getByRole('heading', { name: 'Первый', exact: true }) })
    await first.getByRole('button', { name: /Добавить карточку/ }).click()
    await page.getByLabel('Название карточки').fill('Карточка')
    await page.getByRole('button', { name: 'Создать карточку' }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    const cardTrigger = page.getByRole('button', { name: 'Действия карточки Карточка' })
    await cardTrigger.focus(); await page.keyboard.press('Enter')
    await page.getByRole('menuitem', { name: 'Удалить', exact: true }).click()
    let dialog = page.getByRole('dialog', { name: 'Удалить карточку' })
    await expect(dialog.getByRole('button', { name: 'Отмена' })).toBeFocused()
    await expect(dialog).toContainText('Карточка')
    await expect(dialog.getByRole('combobox')).toHaveCount(0)
    await expect(page.getByRole('combobox')).toHaveCount(0)
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(cardTrigger).toBeFocused()
    await page.keyboard.press('Enter')
    await page.getByRole('menuitem', { name: 'Удалить', exact: true }).click()
    await page.keyboard.press('Tab'); await page.keyboard.press('Enter')
    await expect(dialog).toBeHidden()
    await expect(page.getByRole('button', { name: 'Действия статуса Первый' })).toBeFocused()
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Первый', exact: true })).toBeVisible()
    await expect(page.locator('.work-card')).toHaveCount(0)
    for (const [name, next] of [['Первый', 'Второй'], ['Второй', '']]) {
      const trigger = page.getByRole('button', { name: `Действия статуса ${name}` })
      await trigger.focus(); await page.keyboard.press('Enter')
      await page.getByRole('menuitem', { name: 'Удалить', exact: true }).click()
      dialog = page.getByRole('dialog', { name: 'Удалить статус' })
      await expect(dialog.getByRole('button', { name: 'Отмена' })).toBeFocused()
      await expect(dialog.getByRole('combobox')).toHaveCount(0)
      await page.keyboard.press('Tab'); await page.keyboard.press('Enter')
      await expect(dialog).toBeHidden()
      if (next) await expect(page.getByRole('button', { name: `Действия статуса ${next}` })).toBeFocused()
      else await expect(page.getByRole('button', { name: 'Добавить статус' }).first()).toBeFocused()
    }
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Добавьте первый статус' })).toBeVisible()
    await page.getByRole('button', { name: 'Добавить статус' }).first().click()
    await expect(page.getByRole('dialog', { name: 'Новый статус' })).toBeVisible()
  })
}
