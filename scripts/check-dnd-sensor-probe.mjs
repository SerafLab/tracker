import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'

const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.DND_PROBE_URL ?? 'http://127.0.0.1:4190/tracker/dnd-sensor-probe.html')
  const counters = page.locator('.probe-counters')
  await counters.waitFor()
  const starts = async () => Number(await counters.getAttribute('data-starts'))
  const opens = async () => Number(await counters.getAttribute('data-opens'))
  const source = page.locator('[data-probe-card="card-1"]')
  assert.equal(await source.getAttribute('role'), null, 'li must retain listitem semantics')
  assert.equal(await source.getAttribute('tabindex'), null, 'no extra DnD focus stop')
  assert.equal(await source.locator('a').getAttribute('role'), null, 'link must retain its own semantics')
  await source.locator('a').click()
  assert.equal(await opens(), 1)
  await page.getByRole('button', { name: 'Закрыть карточку' }).click()
  await source.locator('a').focus(); await page.keyboard.press('Enter')
  assert.equal(await opens(), 2); assert.equal(await starts(), 0)
  await page.getByRole('button', { name: 'Закрыть карточку' }).click()
  await source.getByRole('button', { name: 'Меню card-1' }).locator('svg').click()
  await page.getByRole('menuitem').click(); assert.equal(await starts(), 0)
  const coordinates = async () => { await source.scrollIntoViewIfNeeded(); const box = await source.boundingBox(); return { x: box.x + 40, y: box.y + 35 } }
  let point = await coordinates()
  await page.mouse.move(point.x, point.y); await page.mouse.down(); await page.mouse.move(point.x + 4, point.y)
  assert.equal(await starts(), 0, '4px must not activate')
  await page.mouse.up()
  if (await page.getByRole('button', { name: 'Закрыть карточку' }).count()) await page.getByRole('button', { name: 'Закрыть карточку' }).click()
  const beforeDragOpens = await opens()
  point = await coordinates()
  await page.mouse.move(point.x, point.y); await page.mouse.down(); await page.mouse.move(point.x + 15, point.y, { steps: 3 })
  await page.waitForFunction(() => document.querySelector('.probe-counters').dataset.starts === '1')
  assert.equal(await page.locator('[data-dnd-overlay] button').count(), 0)
  const destination = await page.locator('[data-probe-column="Пустой статус"]').boundingBox()
  await page.mouse.move(destination.x + 100, destination.y + 120, { steps: 12 }); await page.mouse.up()
  await page.waitForFunction(() => document.querySelector('[data-probe-column="Пустой статус"] [data-probe-card="card-1"]'))
  assert.equal(await opens(), beforeDragOpens, 'drop must not open the link')
  await page.waitForFunction(() => document.querySelectorAll('.probe-gap').length === 0)
  await source.locator('a').click(); assert.equal(await opens(), beforeDragOpens + 1)
  await page.getByRole('button', { name: 'Закрыть карточку' }).click()
  point = await coordinates()
  await page.mouse.move(point.x, point.y); await page.mouse.down(); await page.mouse.move(point.x + 15, point.y, { steps: 3 })
  await page.waitForFunction(() => document.querySelector('.probe-counters').dataset.starts === '2')
  await page.keyboard.press('Escape'); await page.mouse.up()
  assert.equal(await opens(), beforeDragOpens + 1, 'cancellation must not open the link')
  await page.waitForFunction(() => document.querySelectorAll('.probe-gap').length === 0)
  await source.locator('a').click(); assert.equal(await opens(), beforeDragOpens + 2)
  await page.getByRole('button', { name: 'Закрыть карточку' }).click()
  point = await coordinates()
  await page.mouse.move(point.x, point.y); await page.mouse.down(); await page.mouse.move(point.x + 15, point.y, { steps: 3 })
  await page.waitForFunction(() => document.querySelector('.probe-counters').dataset.starts === '3')
  await page.mouse.move(5, 5, { steps: 8 }); await page.mouse.up()
  assert.equal(await opens(), beforeDragOpens + 2, 'outside drop must not open')
  assert.equal(await page.locator('[data-probe-column="Пустой статус"] [data-probe-card="card-1"]').count(), 1)
  await page.screenshot({ path: '/private/tmp/tracker-dnd-probe-desktop.png' })
  assert.deepEqual(errors, [])
  console.log('PASS: semantic li/link, click/Enter, SVG menu, mouse threshold, drop, cancel, outside and next independent click')
} finally { await browser.close() }
