import { expect, test, type Page } from '@playwright/test'

async function seededBoard(page: Page, en = false) {
  await page.goto('/tracker/')
  await expect(page.getByRole('button', { name: 'Создать проект', exact: true })).toBeVisible()
  if (en) { await page.getByRole('button', { name: 'Настройки', exact: true }).click(); await page.getByRole('combobox').selectOption('en'); await page.keyboard.press('Escape') }
  await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('personal-project-tracker'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error) })
    await new Promise<void>((resolve, reject) => {
      const tx = db.transaction(['projects', 'statuses', 'cards'], 'readwrite')
      tx.objectStore('projects').put({ id: 'panel-project', name: 'Panel project', createdAt: '2026-11-03T00:00:00Z' })
      tx.objectStore('statuses').put({ id: 'panel-status', projectId: 'panel-project', name: 'Todo', position: 0 })
      for (let index = 0; index < 25; index++) tx.objectStore('cards').put({ id: `panel-card-${index}`, statusId: 'panel-status', name: `Card ${index}`, description: index === 0 ? 'Saved description\nhttps://example.com/' + 'very-long-path'.repeat(30) : '', important: false, urgent: false, position: index })
      tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error)
    })
    db.close()
  })
  await page.goto('/tracker/#project/panel-project')
  await expect(page.getByRole('link', { name: 'Card 0', exact: true })).toBeVisible()
}

for (const en of [false, true]) test(`panel history preserves board/editor, switches cards once and reloads as page ${en ? 'en' : 'ru'}`, async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await seededBoard(page, en)
  const board = page.locator('.status-columns')
  await board.evaluate(node => { node.dataset.identity = 'preserved' })
  await page.getByRole('link', { name: 'Card 0', exact: true }).click()
  const panel = page.getByRole('region', { name: en ? 'Card details' : 'Подробности карточки', exact: true })
  await expect(panel).toBeFocused()
  await expect(page.getByRole('heading', { level: 1, name: 'Panel project' })).toBeVisible()
  await expect(board).toHaveAttribute('data-identity', 'preserved')
  const cardUrl = page.url(), initialLength = await page.evaluate(() => history.length)
  const description = panel.getByRole('textbox', { name: en ? 'Card description' : 'Описание карточки', exact: true })
  await description.fill('Uncommitted description')
  await panel.getByRole('button', { name: en ? 'Add note' : 'Добавить заметку', exact: true }).click()
  await panel.getByRole('textbox', { name: en ? 'New note' : 'Новая заметка', exact: true }).fill('Uncommitted note')
  await panel.getByRole('button', { name: en ? 'Open full page' : 'Открыть на всю страницу', exact: true }).click()
  await expect(page.locator('.card-panel')).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: en ? 'Card description' : 'Описание карточки', exact: true })).toHaveValue('Uncommitted description')
  await expect(page.getByRole('textbox', { name: en ? 'New note' : 'Новая заметка', exact: true })).toHaveValue('Uncommitted note')
  await expect(page).toHaveURL(cardUrl)
  expect(await page.evaluate(() => history.length)).toBe(initialLength + 1)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('form', { name: en ? 'Card fields' : 'Поля карточки' }).getByRole('button', { name: en ? 'Save' : 'Сохранить', exact: true }).click()
  await page.getByRole('button', { name: en ? 'Add note' : 'Добавить заметку', exact: true }).click()
  await expect(page.getByRole('textbox', { name: en ? 'New note' : 'Новая заметка', exact: true })).toHaveCount(0)
  await page.goBack()
  await expect(panel).toBeVisible()
  await expect(description).toHaveValue('Uncommitted description')
  await expect(page.locator('.card-description-preview').first()).toHaveText('Uncommitted description')
  await expect(board).toHaveAttribute('data-identity', 'preserved')
  // Switching several cards replaces the panel entry, so one Back closes the panel.
  await page.getByRole('link', { name: 'Card 1', exact: true }).click()
  await expect(panel.getByRole('heading', { name: 'Card 1', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Card 2', exact: true }).click()
  await expect(panel.getByRole('heading', { name: 'Card 2', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.locator('.card-panel')).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Card 2', exact: true })).toBeFocused()
  await page.goForward()
  await expect(panel).toBeVisible()
  await page.reload()
  await expect(page.locator('.card-panel')).toHaveCount(0)
  await expect(page.getByRole('heading', { level: 1, name: 'Card 2' })).toBeVisible()
  await expect(page.getByRole('button', { name: en ? 'Add status' : 'Добавить статус', exact: true })).toHaveCount(0)
})

